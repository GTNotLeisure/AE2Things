package com.asdflj.ae2thing.coremod;

import java.util.List;
import java.util.Map;
import java.util.Set;

import javax.annotation.Nullable;

import com.asdflj.ae2thing.Tags;
import com.google.common.collect.ImmutableMap;
import com.google.common.collect.Maps;
import com.google.common.eventbus.EventBus;
import com.gtnewhorizon.gtnhmixins.IEarlyMixinLoader;
import com.gtnewhorizon.gtnhmixins.builders.IMixins;

import cpw.mods.fml.common.DummyModContainer;
import cpw.mods.fml.common.FMLLog;
import cpw.mods.fml.common.LoadController;
import cpw.mods.fml.common.Loader;
import cpw.mods.fml.common.LoaderState.ModState;
import cpw.mods.fml.common.ModContainer;
import cpw.mods.fml.common.ModMetadata;
import cpw.mods.fml.relauncher.IFMLLoadingPlugin;

@IFMLLoadingPlugin.Name("AE2ThingCore")
@IFMLLoadingPlugin.MCVersion("1.7.10")
@IFMLLoadingPlugin.TransformerExclusions({ "com.asdflj.ae2thing.coremod.AE2ThingCore" })
public class AE2ThingCore extends DummyModContainer implements IFMLLoadingPlugin, IEarlyMixinLoader {

    private static final String MOD_ID = "ae2thing-core";
    private static final String MODULE = "ae2thing_ab";
    private static final String REQUIRED = "Botania";

    private static boolean DEV_ENVIRONMENT;

    private final ModMetadata metadata = new ModMetadata();

    public AE2ThingCore() {
        this.metadata.autogenerated = false;
        this.metadata.modId = MOD_ID;
        this.metadata.name = getName();
        this.metadata.version = getVersion();
        this.metadata.description = "Embedded coremod for AE2Thing";
    }

    @Override
    public String[] getASMTransformerClass() {
        return new String[0];
    }

    @Override
    public String getModContainerClass() {
        return "com.asdflj.ae2thing.coremod.AE2ThingCore";
    }

    @Nullable
    @Override
    public String getSetupClass() {
        return null;
    }

    @Override
    public void injectData(Map<String, Object> data) {
        DEV_ENVIRONMENT = !(boolean) data.get("runtimeDeobfuscationEnabled");
    }

    @Nullable
    @Override
    public String getAccessTransformerClass() {
        return null;
    }

    @Override
    public String getMixinConfig() {
        return "mixins.ae2thing.early.json";
    }

    @Override
    public List<String> getMixins(Set<String> loadedCoreMods) {
        return IMixins.getEarlyMixins(Mixins.class, loadedCoreMods);
    }

    @Override
    public boolean registerBus(final EventBus bus, final LoadController controller) {
        removeAppBotWithoutBotania(controller);
        return true;
    }

    @Override
    public ModMetadata getMetadata() {
        return this.metadata;
    }

    @Override
    public String getModId() {
        return MOD_ID;
    }

    @Override
    public String getName() {
        return "AE2Thing Core";
    }

    @Override
    public String getVersion() {
        return Tags.VERSION;
    }

    @Override
    public String getDisplayVersion() {
        return getVersion();
    }

    private static void removeAppBotWithoutBotania(final LoadController controller) {
        final Loader loader = Loader.instance();
        final ModContainer appBot = loader.namedMods.get(MODULE);
        if (appBot == null || loader.namedMods.containsKey(REQUIRED)) {
            return;
        }
        if (controller.getModState(appBot) != ModState.AVAILABLE) {
            throw new IllegalStateException(MODULE + " was registered before " + MOD_ID);
        }
        FMLLog.info("[AE2Thing] Botania is not installed, skipping embedded mod " + MODULE);
        appBot.setEnabledState(false);
        loader.mods.remove(appBot);
        loader.namedMods = ImmutableMap.copyOf(Maps.filterKeys(loader.namedMods, id -> !MODULE.equals(id)));
    }

    public static boolean isDevEnv() {
        return DEV_ENVIRONMENT;
    }
}
